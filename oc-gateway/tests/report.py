#!/usr/bin/env python3
"""Run the whole suite and write TEST_REPORT.md from the REAL results (nothing is hand-written)."""
import io
import os
import sys
import time
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)


class Rec(unittest.TextTestResult):
    def __init__(self, *a, **k):
        super().__init__(*a, **k); self.rows = []

    def addSuccess(self, t): super().addSuccess(t); self.rows.append((t, "PASS", ""))
    def addFailure(self, t, e): super().addFailure(t, e); self.rows.append((t, "FAIL", self._exc_info_to_string(e, t)[-400:]))
    def addError(self, t, e): super().addError(t, e); self.rows.append((t, "ERROR", self._exc_info_to_string(e, t)[-400:]))
    def addSkip(self, t, r): super().addSkip(t, r); self.rows.append((t, "SKIP", r))


def main():
    suite = unittest.defaultTestLoader.discover(HERE, pattern="test_*.py")
    t0 = time.time()
    res = unittest.TextTestRunner(stream=io.StringIO(), resultclass=Rec, verbosity=0).run(suite)
    out = ["# Test report", "", "Generated by `python3 tests/report.py` on %s. Upstream providers are local fakes (no real quota used)." % time.strftime("%Y-%m-%d %H:%M:%S"), "",
           "**%d tests, %d passed, %d failed, %d errors, %d skipped, %.0fs**" % (res.testsRun, sum(r[1] == "PASS" for r in res.rows),
                                                                               len(res.failures), len(res.errors), len(res.skipped), time.time() - t0), "",
           "| Result | Test |", "|---|---|"]
    for t, status, detail in sorted(res.rows, key=lambda r: r[0].id()):
        out.append("| %s | `%s` |" % (status, t.id().replace("tests.", "")))
    out += ["", "## NOT covered by these tests (be aware)", "",
            "- Real provider APIs (OpenRouter / Groq / NVIDIA): no network in the build sandbox, so behaviour was verified against fakes that mimic the documented OpenAI-compatible protocol.",
            "- Docker image build, docker-compose, Caddy TLS: files are provided but could not be executed in the build sandbox.",
            "- A real OpenCode client session: the OpenCode config follows the documented schema but was not run against the gateway.",
            "- Dashboard rendering in a browser: JavaScript syntax-checked and API-tested only.",
            "- LiteLLM: not used (see docs/ARCHITECTURE.md for why)."]
    failed = [r for r in res.rows if r[1] in ("FAIL", "ERROR")]
    if failed:
        out += ["", "## Failures", ""] + ["### %s\n```\n%s\n```" % (t.id(), d) for t, _, d in failed]
    path = os.path.join(HERE, "..", "TEST_REPORT.md")
    open(path, "w").write("\n".join(out) + "\n")
    print("\n".join(out[:6]))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
